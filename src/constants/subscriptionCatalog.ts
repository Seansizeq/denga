/** Прибирає регістр, пробіли й дефіси — «Apple One», «apple-one» і «appleone» це одне. */
const normalize = (value: string): string =>
  value.toLocaleLowerCase().replace(/[\s\-_.]+/g, '');

const BY_KEY = new Map<string, CatalogService>();
for (const service of SUBSCRIPTION_CATALOG) {
  BY_KEY.set(normalize(service.name), service);
  BY_KEY.set(service.id, service);
  for (const alias of service.aliases) BY_KEY.set(normalize(alias), service);
}

/**
 * Сервіс за назвою підписки. Прив'язки в базі немає навмисно: пошук за назвою
 * підхоплює й ті підписки, які завели руками до появи каталогу.
 */
export const findCatalogService = (name: string | null | undefined): CatalogService | null => {
  if (!name) return null;
  return BY_KEY.get(normalize(name)) ?? null;
};

/**
 * Підказки під час набору назви. Порожній запит віддає весь каталог і не
 * обрізається лімітом: стрічка прокручується вбік, тож нема сенсу ховати
 * половину сервісів від того, хто ще нічого не набрав.
 */
export const searchCatalog = (query: string, limit = 6): CatalogService[] => {
  const q = normalize(query);
  if (!q) return SUBSCRIPTION_CATALOG;
  const starts: CatalogService[] = [];
  const contains: CatalogService[] = [];
  for (const service of SUBSCRIPTION_CATALOG) {
    const keys = [service.name, ...service.aliases].map(normalize);
    if (keys.some((k) => k.startsWith(q))) starts.push(service);
    else if (keys.some((k) => k.includes(q))) contains.push(service);
  }
  return [...starts, ...contains].slice(0, limit);
};
