/** Звичайний такт опитування, коли все гаразд. */
export const POLL_INTERVAL_MS = 5000;

/** Далі за це відступати нема сенсу: людина вже дивиться на застарілі дані. */
export const MAX_BACKOFF_MS = 60_000;

/**
 * Пауза перед наступною спробою після невдачі.
 *
 * Досі опитувач стукав із тим самим інтервалом незалежно від того, відповідає
 * сервер чи ні. Поки клієнт один, це непомітно; на сотнях відкритих екранів
 * недоступний сервер отримує рівно те саме навантаження, що й здоровий, — і
 * піднятися йому це не допомагає.
 *
 * Розкид (jitter) тут не прикраса, а головне. Без нього всі клієнти,
 * що втратили звʼязок одночасно (рестарт сервера — а це кожен деплой),
 * повертаються теж одночасно, рівно однією хвилею. Випадкова частка ділить
 * цю хвилю на рівномірний потік.
 *
 * @param consecutiveFailures скільки спроб підряд не вдалося (з 1)
 * @param random підставляється в тестах
 */
export const backoffDelayMs = (consecutiveFailures: number, random: () => number = Math.random): number => {
  const attempt = Math.max(1, Math.floor(consecutiveFailures));
  const exponential = Math.min(MAX_BACKOFF_MS, POLL_INTERVAL_MS * 2 ** (attempt - 1));
  // Повна випадковість у діапазоні, а не «база плюс трохи»: так хвиля
  // розмазується найрівніше. Нижня межа — звичайний такт, щоб відступ ніколи
  // не виявився агресивнішим за нормальну роботу.
  const jittered = POLL_INTERVAL_MS + random() * Math.max(0, exponential - POLL_INTERVAL_MS);
  return Math.round(jittered);
};
